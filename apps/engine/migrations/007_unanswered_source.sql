-- Разделение источников сигнала о пробеле.
--
-- Запасной детектор (поиск ничего не нашёл) срабатывает на любой реплике без попаданий,
-- включая ответы посетителя в ходе квалификации: «Vreau în jur de 2.80 metri» — это
-- не вопрос без ответа, а ответ на вопрос бота. Директор по продажам открыл бы
-- главный для него список и увидел мусор.
--
-- Сигнал самой модели (report_unanswered) точнее: она формулирует тему своими словами
-- и знает, ответила ли по существу. Его и показываем; запасной остаётся для отладки.
BEGIN;

ALTER TABLE unanswered_log
  ADD COLUMN source text NOT NULL DEFAULT 'model'
  CHECK (source IN ('model', 'fallback'));

CREATE INDEX ON unanswered_log (tenant_id, source, created_at DESC);

COMMIT;
