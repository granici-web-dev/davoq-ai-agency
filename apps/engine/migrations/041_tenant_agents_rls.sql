-- Изоляция арендаторов у таблицы, которая решает доступ.
--
-- Миграция 040 завела `tenant_agents` и забыла единственное, на чём в этом
-- движке держится разделение клиентов. Все пятнадцать тенантных таблиц имеют
-- ENABLE и FORCE ROW LEVEL SECURITY с одной и той же политикой; эта — ни
-- того, ни другого. То есть таблица, отвечающая на вопрос «что этому клиенту
-- разрешено», была единственной без защиты от чтения чужого ответа.
--
-- Сегодня утечки нет: и `loadGrants`, и `syncPlanGrants` фильтруют по
-- tenant_id явно. Но явный фильтр — это дисциплина, а RLS — это то, что
-- работает, когда дисциплина не сработала. Ровно для такого случая FORCE
-- и стоит на остальных таблицах.
--
-- Найдено при первом живом запуске портала, а не чтением кода: в 040 отсутствие
-- этих трёх строк ничем не выделялось.
--
-- Заведение тенантов не ломается: приложение ходит ролью assistwidget_app
-- (NOSUPERUSER, NOBYPASSRLS) и тенантный контекст ставит, а `withOwner`
-- работает владельцем-суперпользователем, который обходит даже FORCE.
BEGIN;

ALTER TABLE tenant_agents ENABLE ROW LEVEL SECURITY;
ALTER TABLE tenant_agents FORCE  ROW LEVEL SECURITY;

-- nullif(): без тенантного контекста current_setting отдаёт пустую строку,
-- и ::uuid падал бы с нечитаемым «invalid input syntax». С ним сравнение
-- даёт NULL, то есть ноль строк. Тот же текст, что у остальных политик, —
-- расхождение здесь было бы расхождением в правиле, а не в написании.
CREATE POLICY tenant_isolation ON tenant_agents
  USING (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid)
  WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid);

COMMIT;
