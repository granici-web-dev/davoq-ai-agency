-- Конфигурация клиента: то, что задаётся при заведении.
--
-- Три колонки, три разные вещи:
--
-- profile — факты о клиенте, которые попадают в промпт: шоурумы, часы работы,
--   тон общения. Раньше их не было нигде, и бот про шоурумы знал ровно столько,
--   сколько нашлось в материалах.
--
-- retrieval_overrides — пороги поиска этого клиента поверх порогов ниши.
--   Пусто у большинства: значение ниши подходит, пока корпус обычный.
--
-- applied_config — снимок того, что в последний раз записал онбординг.
--   Нужен, чтобы повторное применение отличило «мы это ещё не применяли»
--   от «клиент поменял это сам в панели». Второе затирать нельзя: приветствие
--   и адрес для заявок клиент правит сам, и релиз не имеет права их вернуть.
BEGIN;

ALTER TABLE tenants
  ADD COLUMN profile             jsonb NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN retrieval_overrides jsonb NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN applied_config      jsonb;

COMMIT;
