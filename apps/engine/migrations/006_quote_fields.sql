-- Квалификация под расчёт цены (Phase 3.5).
-- Цену у клиента считает продавец, задавая вопросы. Бот ведёт тот же разговор
-- и передаёт продавцу заполненный бриф вместо голого контакта.
BEGIN;

-- Набор вопросов задаёт тенант, а не код: у мебельщика это метраж и наполнитель,
-- у автосервиса — марка и год. Захардкоженный список сделал бы фичу заплаткой
-- под одного клиента.
ALTER TABLE tenants ADD COLUMN quote_fields jsonb NOT NULL DEFAULT '[]'::jsonb;
-- [{ key, label, description, required }]

-- Вилки цен — текстом, отдельно от базы знаний: они попадают в системный промпт,
-- а не в поиск, потому что нужны в каждом разговоре про цену, а не когда совпадут слова.
ALTER TABLE tenants ADD COLUMN price_guidance text NOT NULL DEFAULT '';

-- Полнота брифа: лид с шестью ответами и лид с одним email — разный товар
-- для отдела продаж, и в списке заявок это должно быть видно сразу.
ALTER TABLE leads ADD COLUMN quote_completeness integer NOT NULL DEFAULT 0;

COMMIT;
