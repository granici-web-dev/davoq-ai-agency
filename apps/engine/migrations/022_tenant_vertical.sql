-- Ниша тенанта.
--
-- До сих пор сценарий ниши существовал только как значения, набитые в
-- quote_fields и price_guidance вручную. Теперь у тенанта есть ссылка на
-- шаблон вертикали, и обновление шаблона доходит до всех клиентов ниши,
-- а не переписывается каждому заново.
BEGIN;

ALTER TABLE tenants ADD COLUMN vertical text;

-- Существующие тенанты — мебельные: продукт запускался на мебельном пилоте.
-- Ставим явно, а не дефолтом колонки: у следующей ниши дефолт «мебель»
-- был бы молчаливой ошибкой.
UPDATE tenants SET vertical = 'furniture' WHERE vertical IS NULL;

COMMIT;
