-- Какое письмо о конце пробного периода уже отправлено.
--
-- Без этой отметки напоминание уходило бы при каждом проходе планировщика —
-- то есть раз в час, шесть дней подряд. Письмо, приходящее шесть раз в день,
-- перестают читать раньше, чем оно становится важным.
--
-- Хранится ступень, а не флаг: ступеней три, и «за три дня» не отменяет
-- «в последний день».
BEGIN;

ALTER TABLE tenants ADD COLUMN trial_notice text;

COMMENT ON COLUMN tenants.trial_notice IS
  'Последняя отправленная ступень напоминания: soon | last_day | expired. NULL — не отправляли.';

COMMIT;
