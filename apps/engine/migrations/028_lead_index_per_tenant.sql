-- Уникальность заявки на разговор была общей на всю платформу, а не внутри клиента.
--
-- Разговор — это UUID, который виджет показывает посетителю. Отправка заявки
-- принимала любой такой UUID без проверки принадлежности, а `Origin` подделывается
-- обычным curl. Значит, посторонний мог записать клиенту B заявку с идентификатором
-- разговора клиента A — и настоящая заявка A по этому разговору переставала
-- сохраняться навсегда: ON CONFLICT бился о строку, которой под RLS не видно,
-- и вся транзакция ответа откатывалась.
--
-- Ключ становится составным. Проверка принадлежности разговора сделана в коде
-- отдельно; здесь — то, что делает столкновение между клиентами невозможным
-- даже если проверку однажды снимут.
BEGIN;

DROP INDEX IF EXISTS leads_one_per_conversation;

CREATE UNIQUE INDEX leads_one_per_conversation
  ON leads (tenant_id, conversation_id) WHERE conversation_id IS NOT NULL;

COMMIT;
