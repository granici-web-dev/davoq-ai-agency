-- Новая лестница тарифов.
--
-- Правило миграции тарифов: маппинг СОХРАНЯЕТ текущее поведение, спорное
-- решает человек. Клиент, проснувшийся утром без функции, за которую вчера
-- платил, — это не «мы обновили лестницу», это отказ в обслуживании.
BEGIN;

/**
 * Данные не меняются, и это проверено, а не предположено.
 *
 *   starter  — было «чат-бот», стало «чат-бот». Ничего не потеряно.
 *   pro      — было «чат-бот + Drive», стало «+ конфигуратор». Только прибавка.
 *   business — было «+ коннекторы + старшая модель», стало «+ follow-up
 *              и этапы производства». Тоже только прибавка.
 *
 * Поэтому UPDATE здесь один — защитный, на значения вне лестницы. Такое
 * значение появиться не должно, но если появилось, тенант обязан оказаться
 * на САМОМ ДЕШЁВОМ тарифе, а не на самом дорогом: заниженный он заметит
 * и позвонит, завышенный не заметит никто, и платить за старшую модель
 * будем мы.
 */
UPDATE tenants
   SET plan = 'starter'
 WHERE plan NOT IN ('starter', 'pro', 'business', 'enterprise');

/**
 * Цены выросли: starter 49 → 79, pro 99 → 199, business 299 → 349.
 *
 * Действующей подписки это НЕ КАСАЕТСЯ: Stripe списывает по цене, записанной
 * в самой подписке, и наша таблица на неё не влияет. Пока клиент не сменит
 * тариф, он платит столько, на сколько подписался.
 *
 * Но панель показывает цену из кода, и у подписчика на старой цене она
 * разойдётся с его счётом. Подписчиков сейчас нет — проверено запросом ниже,
 * и если он что-то найдёт, миграция скажет об этом вслух, а не промолчит.
 */
DO $$
DECLARE affected int;
BEGIN
  SELECT count(*) INTO affected
    FROM tenants
   WHERE subscription_id IS NOT NULL
     AND subscription_status IN ('active', 'past_due');

  IF affected > 0 THEN
    RAISE WARNING 'тенантов с действующей подпиской: % — цену в панели надо сверить с ценой в Stripe вручную', affected;
  END IF;
END $$;

-- Потолок оферт в месяц. Пусто — берётся из тарифа, как и потолок сообщений.
ALTER TABLE tenants ADD COLUMN monthly_offer_cap integer;

COMMENT ON COLUMN tenants.monthly_offer_cap IS
  'Индивидуальный потолок оферт в месяц. NULL — потолок тарифа.';

COMMIT;
