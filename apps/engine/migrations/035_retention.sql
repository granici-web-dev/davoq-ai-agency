-- Когда подписка была отменена и что происходит с данными.
--
-- До сих пор не происходило ничего: переписки, заявки и материалы лежали
-- вечно. Это плохо с двух сторон сразу. Со стороны клиента — его посетители
-- не соглашались на бессрочное хранение своих вопросов и телефонов. Со стороны
-- диска — он кончится, и кончится тихо.
--
-- Отметка нужна именно об отмене: удалять по subscription_status нельзя,
-- потому что он ничего не говорит о том, КОГДА клиент ушёл, а срок хранения
-- отсчитывается от этого дня.
BEGIN;

ALTER TABLE tenants ADD COLUMN canceled_at timestamptz;

COMMENT ON COLUMN tenants.canceled_at IS
  'День отмены подписки. От него отсчитывается срок хранения данных. NULL — не отменена.';

-- Действующим клиентам отметка не нужна и вредна: непустое значение здесь
-- означает обратный отсчёт до удаления.
UPDATE tenants SET canceled_at = now() WHERE subscription_status = 'canceled';

COMMIT;
