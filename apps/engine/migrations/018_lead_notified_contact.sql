-- Контакт, который реально ушёл письмом.
--
-- Найдено проверкой: посетитель дал телефон, письмо ушло, а через две реплики
-- он написал «извините, ошибся, правильный такой-то». В базе номер исправился,
-- в письме остался старый — и продавец набирает не тот номер, никого не находит
-- и закрывает заявку как мёртвую.
--
-- Ссылка на разговор это не спасает: с телефона нажимают на номер в письме,
-- а не открывают панель. Поэтому смена контакта — единственный повод отправить
-- второе письмо. Уточнённый метраж или обивка таким поводом не являются:
-- они не ведут к действию с неверными данными.
BEGIN;

ALTER TABLE leads ADD COLUMN notified_contact text;

-- Уже отправленным письмам приписываем их текущий контакт: иначе первое же
-- задание после миграции сочло бы их изменившимися и отправило дубль.
UPDATE leads
   SET notified_contact = concat_ws('|', nullif(regexp_replace(coalesce(phone, ''), '\D', '', 'g'), ''),
                                         nullif(lower(coalesce(email, '')), ''))
 WHERE notified_at IS NOT NULL;

COMMIT;
