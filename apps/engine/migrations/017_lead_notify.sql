-- Куда слать. В базе, а не в переменной окружения: продукт белолейбловый,
-- у каждого тенанта свой отдел продаж, и адрес меняет сам клиент из панели.
ALTER TABLE tenants ADD COLUMN lead_notify_email text;

-- Отметка отправки. Нужна по двум причинам, и обе про честность:
-- повтор задания не может отправить второе письмо, а панель показывает,
-- ушло письмо или нет, вместо того чтобы молча делать вид, что ушло.
ALTER TABLE leads
  ADD COLUMN notified_at  timestamptz,
  ADD COLUMN notify_error text;

