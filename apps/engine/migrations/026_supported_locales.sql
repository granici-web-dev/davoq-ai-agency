-- Языки, на которых клиент готов разговаривать.
--
-- Виджет до сих пор выбирал язык интерфейса по настройкам браузера из четырёх
-- встроенных, не спрашивая клиента. Для румынского производителя это значит:
-- посетитель с русским браузером получает русское приветствие, спрашивает
-- по-русски — и поиск не находит ничего, потому что материалы румынские,
-- а модель эмбеддингов одноязычна (замерено: 0.316 против 0.660).
--
-- Пустой список читается как «только язык по умолчанию». Осознанно строгий
-- вариант: приглашать на языке, на котором не сможешь ответить, хуже, чем
-- поздороваться не на родном.
BEGIN;

ALTER TABLE tenants ADD COLUMN supported_locales text[] NOT NULL DEFAULT '{}';

UPDATE tenants SET supported_locales = ARRAY[locale_default];

COMMIT;
