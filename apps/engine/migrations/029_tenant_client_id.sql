-- Устойчивый ключ клиента для команды apply.
--
-- Тенант искался по имени, а UNIQUE на имени не было. Два следствия, оба
-- проявляются на втором клиенте и ни одно — на первом:
--
--   1. Одноимённый второй клиент перезаписывал домены и настройки первого,
--      и команда рапортовала «ПРИМЕНЕНО».
--   2. Переименование клиента в config.yaml заводило второго тенанта с новым
--      публичным ключом, а сниппет на сайте продолжал указывать на старого.
--      То есть переименование выглядело как успех и означало мёртвый виджет.
--
-- Ключом становится идентификатор из clients/<id>/config.yaml — он не меняется
-- при переименовании, потому что это имя папки, а не вывеска.
BEGIN;

ALTER TABLE tenants ADD COLUMN client_id text;

CREATE UNIQUE INDEX tenants_client_id_key ON tenants (client_id) WHERE client_id IS NOT NULL;

-- Имя больше не ключ, но и дубликаты имён — почти всегда ошибка оператора.
-- Не UNIQUE, а индекс для поиска: apply опирается на него, когда client_id
-- ещё не проставлен, и требует ровно одного совпадения.
CREATE INDEX tenants_name_idx ON tenants (name);

COMMIT;
