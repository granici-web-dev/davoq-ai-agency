-- Отметка о протечке языка.
--
-- Бот иногда отвечает на языке своих инструкций, а не посетителя. После правок
-- промпта это примерно один ответ из пятидесяти на самой трудной развилке —
-- но «примерно» здесь моя оценка по трёмстам синтетическим прогонам, а не
-- измерение на живом трафике. Колонка нужна, чтобы пилот показал настоящую
-- цифру, а не мою.
--
--   'retried' — поймано до отправки, ответ перегенерирован, посетитель видел верный
--   'leak'    — обнаружено, но исправить уже нельзя, посетитель видел чужой язык
--   NULL      — обычный ответ
BEGIN;

ALTER TABLE messages ADD COLUMN language_flag text
  CHECK (language_flag IN ('retried', 'leak'));

CREATE INDEX ON messages (tenant_id, created_at DESC) WHERE language_flag IS NOT NULL;

COMMIT;
