/**
 * Текст, приходящий снаружи, перед тем как попасть в базу.
 *
 * Postgres не хранит нулевой байт в `text` — не обрезает, а отвергает всю
 * команду. Пока это не проверялось, одно сообщение с нулевым байтом проходило
 * весь путь: ответ генерировался, оплачивался и уходил посетителю, а затем
 * падала запись, и транзакция откатывалась целиком — разговор, реплики, заявка,
 * письмо. Вместе с ними откатывался счётчик расхода, то есть месячный потолок
 * сообщений не срабатывал никогда: скрипт мог жечь токены бесконечно.
 * Проверено на живом эндпоинте до починки: 0 сохранённых разговоров.
 *
 * Отсюда два правила. Чистить на входе, а не у самой записи: мест записи много,
 * а входов мало. И молча, без отказа посетителю: он этот байт не набирал,
 * сообщать ему не о чем.
 */

/**
 * Убирает то, что база откажется хранить, и обрезает до потолка.
 *
 * Нулевой байт база отвергает; остальные управляющие символы она хранит, но
 * в переписке они не значат ничего и ломают выгрузку в CSV. Перевод строки
 * и табуляция сохраняются — они часть текста.
 */
export function sanitizeText(value: string, maxChars = 0): string {
  const cleaned = value.replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '');
  return maxChars > 0 ? cleaned.slice(0, maxChars) : cleaned;
}

/** То же для необязательного поля: пустая строка после чистки — это null. */
export function sanitizeOptional(value: string | undefined | null, maxChars = 0): string | null {
  if (typeof value !== 'string') return null;
  const cleaned = sanitizeText(value, maxChars).trim();
  return cleaned === '' ? null : cleaned;
}

/**
 * Потолок на сообщение посетителя. Не защита от длинного вопроса, а защита от
 * того, что за ним стоит: длина не проверялась нигде, а у эмбеддера свой лимит,
 * и запрос падал в 500 ещё до обращения к модели.
 */
export const MESSAGE_MAX_CHARS = 4000;
