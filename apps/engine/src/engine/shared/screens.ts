/**
 * Экраны панели — один список на всех.
 *
 * Их было два: один в панели, другой в валидации конфига. Они уже разъезжались,
 * и это ровно тот случай, когда ошибку замечает не разработчик, а клиент:
 * экран, который нельзя скрыть, или опечатка в списке скрытых, которая молчит.
 *
 * Названия здесь не лежат: они переводятся, а перевод — дело панели.
 */
export const SCREENS = [
  'kb', 'drive', 'aspect', 'connectors', 'chats', 'analytics',
  // Акции: экран есть только у тенантов с конфигуратором. Скрывается не
  // тарифом, а наличием конфигуратора — подтверждать нечего там, где нечего
  // и применять.
  'promotions',
  'install', 'subscription',
] as const;

export type Screen = (typeof SCREENS)[number];

export const isScreen = (value: string): value is Screen =>
  (SCREENS as readonly string[]).includes(value);
