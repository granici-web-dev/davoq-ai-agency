/**
 * Потолок на одновременные диалоги.
 *
 * Вызов модели длится секунды и всё это время занимает место: соединение
 * с базой на входе и выходе, память под поток, оплаченные токены. Пока потолка
 * не было, число одновременных диалогов задавал не сервер, а тот, кто прислал
 * запросы, — и простой цикл из ста curl'ов клал чат и панель всем клиентам
 * сразу, потому что пул с базой один на процесс.
 *
 * Потолков два, и второй важнее первого. Общий бережёт процесс. Потолок на
 * клиента бережёт клиентов друг от друга: без него один арендатор — или один
 * скрипт на его сайте — занимает весь запас, и остальные получают отказ
 * за чужую вину. Ровно та беда, ради которой всё это разделение на тенантов
 * и затевалось.
 */

// Числа пилотные и настраиваются переменными окружения. Ориентир — не база
// (соединение на время работы модели больше не удерживается), а память процесса
// и пропускная способность Bedrock: сорок одновременных потоков упрутся
// в ограничение аккаунта раньше, чем в наш сервер.
const MAX_TOTAL = Number(process.env.CHAT_MAX_CONCURRENT ?? 32);
const MAX_PER_TENANT = Number(process.env.CHAT_MAX_PER_TENANT ?? 12);

let total = 0;
const perTenant = new Map<string, number>();

export interface Slot {
  release: () => void;
}

/**
 * Занять место или получить отказ. Ожидания в очереди нет намеренно: посетитель,
 * которому не хватило места, должен увидеть это сразу и повторить, а не стоять
 * в очереди, о которой он не знает.
 */
export function acquireSlot(tenantId: string): Slot | null {
  const mine = perTenant.get(tenantId) ?? 0;
  if (total >= MAX_TOTAL || mine >= MAX_PER_TENANT) return null;

  total++;
  perTenant.set(tenantId, mine + 1);

  let released = false;
  return {
    release(): void {
      // Освобождение вызывается из finally, а finally бывает достижим дважды
      // при ошибке внутри самого finally. Двойной release увёл бы счётчик
      // в минус и тихо снял потолок.
      if (released) return;
      released = true;
      total--;
      const left = (perTenant.get(tenantId) ?? 1) - 1;
      if (left <= 0) perTenant.delete(tenantId);
      else perTenant.set(tenantId, left);
    },
  };
}

/** Для журнала и проверок. */
export const slotStats = (): { total: number; tenants: number } => ({
  total,
  tenants: perTenant.size,
});

/** Сколько диалогов этого клиента прямо сейчас в работе, вместе с текущим. */
export const inFlightFor = (tenantId: string): number => perTenant.get(tenantId) ?? 0;

/**
 * Исчерпан ли месячный потолок сообщений — с учётом тех, что ещё в работе.
 *
 * Отдельной функцией и без базы, потому что вся суть здесь в арифметике,
 * а не в запросе.
 *
 * Прежде потолок читался из базы в начале запроса, а увеличивался в конце —
 * между ними секунды работы модели. Двенадцать одновременных диалогов
 * читали одно и то же «ещё не исчерпан» и проходили все, то есть потолок
 * перепрыгивался ровно на число одновременных. Это единственный пункт,
 * который прошлое враждебное ревью оставило открытым сознательно.
 *
 * Считать нечем, кроме счётчика одновременных, — и он уже есть: «в работе»
 * и «займёт место в квоте» это одно и то же множество. Текущий запрос свой
 * слот уже занял, поэтому вычитается: он тот, про кого сейчас решают.
 *
 * Дойти до потолка можно, перейти нельзя: при `used + others === cap` текущий
 * запрос стал бы (cap + 1)-м.
 *
 * Счётчик в памяти процесса, как и всё остальное здесь. Копий API сейчас
 * одна; станет несколько — перепрыгнуть можно будет на их число, и тогда
 * это надо будет переносить в базу отдельной строкой брони.
 */
export function quotaExhausted(used: number, cap: number, inFlight: number): boolean {
  const others = Math.max(0, inFlight - 1);
  return used + others >= cap;
}
