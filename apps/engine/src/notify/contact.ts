/**
 * Контакт в сравнимом виде. «0745 112 233» и «0745112233» — один и тот же
 * номер: сравнивать их как строки значило бы слать второе письмо из-за пробела.
 *
 * Отдельным модулем от письма: сравнение нужно в пути обработки сообщения,
 * и тянуть туда почтовый транспорт ради одной функции незачем.
 */
export const contactKey = (lead: { phone?: string | null; email?: string | null }): string =>
  [lead.phone?.replace(/\D/g, '') ?? '', lead.email?.trim().toLowerCase() ?? '']
    .filter(Boolean)
    .join('|');
